#!/usr/bin/env bash
# Print markdown report for built EasyTier SPKs (INFO, privilege, glibc, hashes).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SPK_DIR="${1:-${ROOT}/.build/spksrc/packages}"
OUT="${2:-}"

shopt -s nullglob
spks=("${SPK_DIR}"/EasyTier_*.spk)
if [ "${#spks[@]}" -eq 0 ]; then
  spks=("${ROOT}"/.build/spksrc/spk/EasyTier/*.spk)
fi
if [ "${#spks[@]}" -eq 0 ]; then
  echo "No EasyTier_*.spk found under ${SPK_DIR}" >&2
  exit 1
fi

emit() {
  if [ -n "${OUT}" ]; then
    printf '%s\n' "$@" >>"${OUT}"
  else
    printf '%s\n' "$@"
  fi
}

[ -n "${OUT}" ] && : >"${OUT}"

emit "### EasyTier SPK build report"
emit ""

for spk in "${spks[@]}"; do
  base="$(basename "${spk}")"
  size="$(stat -c%s "${spk}" 2>/dev/null || stat -f%z "${spk}")"
  sha="$(sha256sum "${spk}" | awk '{print $1}')"
  work="$(mktemp -d)"

  tar -xzf "${spk}" -C "${work}" package.tgz INFO 2>/dev/null || tar -xzf "${spk}" -C "${work}" INFO
  if [ -f "${work}/package.tgz" ]; then
    tar -xzf "${work}/package.tgz" -C "${work}" \
      conf/privilege bin/easytier-core bin/helper/caphelper 2>/dev/null || true
  fi

  emit "#### \`${base}\`"
  emit ""
  emit "| Field | Value |"
  emit "| --- | --- |"
  emit "| Size (bytes) | ${size} |"
  emit "| SHA-256 | \`${sha}\` |"
  if [ -f "${work}/INFO" ]; then
    while IFS= read -r line; do
      [ -z "${line}" ] && continue
      case "${line}" in
        arch=*|version=*|os_min_ver=*|displayname=*|arch_pkg_ver=*|maintainer=*|distributor=*)
          key="${line%%=*}"
          val="${line#*=}"
          emit "| INFO ${key} | \`${val}\` |"
          ;;
      esac
    done <"${work}/INFO"
  fi
  emit ""
  if [ -f "${work}/conf/privilege" ]; then
    emit "**conf/privilege:**"
    emit ""
    emit '```json'
    while IFS= read -r line; do emit "${line}"; done <"${work}/conf/privilege"
    emit '```'
    emit ""
  fi
  if [ -f "${work}/bin/easytier-core" ] && [ -f "${work}/bin/helper/caphelper" ]; then
    emit "**GLIBC gate:**"
    emit ""
    emit '```'
    glibc_log="$("${ROOT}/scripts/test-easytier-glibc-max.sh" \
      "${work}/bin/easytier-core" "${work}/bin/helper/caphelper" 2>&1 || true)"
    while IFS= read -r line; do
      [ -n "${line}" ] && emit "${line}"
    done <<<"${glibc_log}"
    emit '```'
    emit ""
  fi

  rm -rf "${work}"
done

emit "_Generated by \`scripts/report-easytier-spk-artifacts.sh\` on $(date -u +%Y-%m-%dT%H:%MZ)_"

if [ -n "${OUT}" ]; then
  echo "Wrote ${OUT}"
fi